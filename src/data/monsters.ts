export function createInitialMonster(speciesId: string, level: number = 5, nickname?: string) {
  const species = MONSTERS_DATABASE[speciesId];
  if (!species) throw new Error(`Species not found: ${speciesId}`);

  const statMultiplier = 1 + (level - 1) * 0.12;
  const stats = {
    hp: Math.floor(species.baseStats.hp * statMultiplier),
    attack: Math.floor(species.baseStats.attack * statMultiplier),
    defense: Math.floor(species.baseStats.defense * statMultiplier),
    spAttack: Math.floor(species.baseStats.spAttack * statMultiplier),
    spDefense: Math.floor(species.baseStats.spDefense * statMultiplier),
    speed: Math.floor(species.baseStats.speed * statMultiplier),
  };

  return {
    instanceId: 'mon_' + Math.random().toString(36).substring(2, 9),
    speciesId,
    nickname: nickname || species.name,
    level,
    exp: 0,
    maxExp: level * 80,
    currentHp: stats.hp,
    maxHp: stats.hp,
    stats,
    friendship: 50,
    moves: [...species.moves],
    moveCooldowns: {},
    isMega: false,
    caughtWithBall: 'poke_sphere',
    caughtAt: 'Laboratório Costeiro',
  };
}
